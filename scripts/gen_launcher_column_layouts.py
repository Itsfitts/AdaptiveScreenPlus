# -*- coding: utf-8 -*-
"""
Derives 5 / 6 / 7 column layouts for the "Cover Launcher" widget from the 4-column version.

── Why this script is needed ──────────────────────────────────────────
The numColumns property of GridView in widget layouts **cannot be changed at runtime**:
setNumColumns lacks the @RemotableViewMethod annotation, and RemoteViews on targetSdk 28+
refuses reflective calls to it (see comments at top of widget_launcher.xml). Therefore,
"column count" in widgets relies on swapping layout files — four files with nearly identical
content except for numColumns.

Manually maintaining four files would inevitably lead to drift. Thus, they are derived from
the 4-column version: **widget_launcher.xml is the single source of truth**. After modifying it,
simply rerun this script.

⚠ When adding column options (e.g. 8 columns): modify NUMBERS here, LauncherPrefs.COLUMN_CHOICES,
  and CoverLauncherProvider.layoutFor simultaneously.

── Usage ──────────────────────────────────────────────────────────────
    python ExtDisplayRotator/scripts/gen_launcher_column_layouts.py

Output: widget_launcher_c5.xml / _c6.xml / _c7.xml (overwritten)
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT_DIR = os.path.join(HERE, "..", "app", "src", "main", "res", "layout")

SRC = os.path.join(LAYOUT_DIR, "widget_launcher.xml")

# Column numbers to derive
NUMBERS = (5, 6, 7)

# Header comments to swap (the rest is copied verbatim)
TITLE_FROM = u"RemoteViews layout for widget (4 columns)"
BODY_FROM = (u"This file has 4 columns, with\n"
             u"  widget_launcher_c5.xml / _c6.xml / _c7.xml inflated by CoverLauncherProvider\n"
             u"  based on settings. If modifying any of these four, remember to update all four.")

BODY_TO = (u"This file is **derived** from widget_launcher.xml with only numColumns changed.\n"
           u"  Do not edit this file directly — modify the 4-column version and rerun gen_launcher_column_layouts.py.\n"
           u"  CoverLauncherProvider inflates one of the four based on settings.")


def main():
    src_path = os.path.normpath(SRC)
    if not os.path.exists(src_path):
        print("Source file not found: " + src_path)
        return 1

    with io.open(src_path, encoding="utf-8") as f:
        src = f.read()

    if u'android:numColumns="4"' not in src:
        print(u"numColumns=\"4\" not found in source file, please check widget_launcher.xml")
        return 1
    if TITLE_FROM not in src:
        print(u"Header comment title mismatch, update TITLE_FROM in script")
        return 1
    if BODY_FROM not in src:
        print(u"⚠ Header column explanation did not match — update BODY_FROM in script"
              u" to match widget_launcher.xml, otherwise derived comments will keep old phrasing")

    for n in NUMBERS:
        out = src.replace(TITLE_FROM, u"RemoteViews layout for widget (%d columns)" % n)
        out = out.replace(u'android:numColumns="4"', u'android:numColumns="%d"' % n)
        if BODY_FROM in out:
            out = out.replace(BODY_FROM, BODY_TO)
        else:
            print(u"⚠ %d column header comment mismatch, keeping original text" % n)

        dst = os.path.join(LAYOUT_DIR, "widget_launcher_c%d.xml" % n)
        with io.open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print(u"Wrote %s  (%d bytes)" % (os.path.basename(dst), len(out.encode("utf-8"))))

    print(u"Done: %d layouts with matching structure, differing only in numColumns" % (len(NUMBERS) + 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
